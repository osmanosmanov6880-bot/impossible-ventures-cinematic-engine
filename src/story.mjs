export const ALL_IDS = Object.freeze(Object.keys(STORY));
export function getScene(id){return STORY[id] ?? null;}
export function getWorld(id){return WORLDS.find(w=>w.id===id) ?? null;}
export function assertStory(){
  if(ALL_IDS.length!==18 || WORLDS.length!==7)throw Error('Invalid cinematic story inventory');
  for(let i=0;i<18;i++){
    const id='s'+String(i).padStart(2,'0');
    const s=getScene(id);
    if(!s||!s.frame.endsWith('shot_'+String(i).padStart(2,'0')+'.svg'))throw Error('Missing scene '+id);
    for(const field of ['title','subtitle','narration']){
      if(LOCALES.some(lang=>typeof s[field][lang]!=='string'||!s[field][lang].trim()))
        throw Error('Incomplete localization '+id+' '+field);
    }
    if(s.kind==='world'){
      if(!s.fragment||s.choices.length!==2||!s.detailLabel||!s.detail)throw Error('Incomplete world '+id);
      for(const c of s.choices)if(LOCALES.some(lang=>!c.label[lang]||!c.consequence[lang]))throw Error('Missing choice translation '+id);
    }
  }
  return {scenes:18,worlds:7,locales:3,endings:2};
}
